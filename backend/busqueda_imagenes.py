def convertir_a_diccionario(valor: Any) -> dict:
    if isinstance(valor, dict):
        return valor

    if hasattr(valor, "model_dump"):
        return valor.model_dump()

    return {}


def texto_seguro(valor: Any) -> str:
    if valor is None:
        return ""

    texto = str(valor).strip()

    if texto.casefold() in {"none", "null", "undefined"}:
        return ""

    return texto


def normalizar_texto(texto: str) -> str:
    texto_normalizado = unicodedata.normalize(
        "NFKD",
        texto_seguro(texto),
    )

    return texto_normalizado.encode(
        "ascii",
        "ignore",
    ).decode("ascii").lower()


def limpiar_consultas(busquedas: list[str]) -> list[str]:
    consultas = []
    consultas_vistas = set()

    for busqueda in busquedas:
        consulta = texto_seguro(busqueda)
        clave = normalizar_texto(consulta)
        clave = re.sub(r"\s+", " ", clave).strip()

        if not consulta or not clave or clave in consultas_vistas:
            continue

        consultas_vistas.add(clave)
        consultas.append(consulta)

        if len(consultas) >= MAXIMO_CONSULTAS:
            break

    return consultas


def obtener_modo_busqueda() -> str:
    modo = os.getenv(
        VARIABLE_MODO,
        MODO_PRUEBA,
    ).strip().casefold()

    if modo not in {MODO_PRUEBA, MODO_REAL}:
        raise ValueError(
            f"{VARIABLE_MODO} debe valer "
            f"'{MODO_PRUEBA}' o '{MODO_REAL}'."
        )

    return modo


def obtener_cliente() -> OpenAI:
    api_key = os.getenv("OPENAI_API_KEY", "").strip()

    if not api_key:
        raise ValueError(
            "Falta OPENAI_API_KEY para realizar una búsqueda real."
        )

    return OpenAI(
        api_key=api_key,
        max_retries=0,
        timeout=60.0,
    )


